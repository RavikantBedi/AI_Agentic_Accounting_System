class MockProvider(LLMProvider):
    """Always-available deterministic provider."""

    name = "mock"
    is_local = True
    requires_key = False

    def __init__(self, model: str = "deterministic-v1", timeout: float = 5.0):
        super().__init__(model, timeout)

    async def available(self) -> bool:
        return True

    async def complete(
        self,
        messages: list[Message],
        *,
        temperature: float = 0.1,
        max_tokens: int = 2048,
        json_mode: bool = False,
    ) -> LLMResponse:
        started = time.perf_counter()
        prompt = "\n".join(m.content for m in messages if m.role != "system")
        context = _parse_context(prompt)
        task = _detect_task(prompt, context)

        handler = {
            "categorise": self._categorise,
            "explain_variance": self._explain_variance,
            "summarise": self._summarise,
            "reconcile": self._reconcile,
            "extract_document": self._extract_document,
            "answer_question": self._answer_question,
            "tds_section": self._tds_section,
            "close_summary": self._close_summary,
        }.get(task, self._unknown)

        payload = handler(prompt, context)
        payload.setdefault("provider_note", "Generated by the deterministic Mock provider.")

        return LLMResponse(
            text=json.dumps(payload, ensure_ascii=False),
            provider=self.name,
            model=self.model,
            prompt_tokens=len(prompt.split()),
            completion_tokens=40,
            latency_ms=int((time.perf_counter() - started) * 1000),
            finish_reason="stop",
        )

    # ----------------------------------------------------------- handlers --

    def _categorise(self, prompt: str, context: dict) -> dict:
        """Pick from the candidate accounts supplied in the context."""
        description = str(context.get("description", "")).lower()
        candidates = context.get("candidate_accounts") or []

        if not candidates:
            return {
                "insufficient_evidence": True,
                "reasoning": "No candidate accounts were supplied, so no category can be chosen.",
            }

        best_account = None
        best_score = 0
        matched_keyword = ""

        for keyword, hints in CATEGORY_HINTS.items():
            if keyword not in description:
                continue
            for candidate in candidates:
                name = str(candidate.get("name", "")).lower()
                score = sum(3 for hint in hints if hint in name)
                if score > best_score:
                    best_score, best_account, matched_keyword = score, candidate, keyword

        if best_account is None:
            # Direct word overlap with an account name is the weaker fallback.
            words = {w for w in re.findall(r"[a-z]{4,}", description)}
            for candidate in candidates:
                name_words = set(re.findall(r"[a-z]{4,}", str(candidate.get("name", "")).lower()))
                overlap = len(words & name_words)
                if overlap > best_score:
                    best_score, best_account = overlap, candidate

        if best_account is None or best_score == 0:
            return {
                "insufficient_evidence": True,
                "reasoning": (
                    "The description does not match any of the supplied accounts closely "
                    "enough to categorise it confidently."
                ),
            }

        confidence = 0.80 if matched_keyword else 0.55
        return {
            "account_id": best_account.get("id"),
            "account_code": best_account.get("code"),
            "account_name": best_account.get("name"),
            "confidence": confidence,
            "reasoning": (
                f"'{matched_keyword}' in the description maps to "
                f"{best_account.get('name')}."
                if matched_keyword
                else f"The description shares wording with {best_account.get('name')}."
            ),
        }

    def _explain_variance(self, prompt: str, context: dict) -> dict:
        """Describe the supplied drivers factually, ranked by magnitude."""
        drivers = context.get("drivers") or []
        metric = context.get("metric", "Net profit")
        change_percent = context.get("change_percent")
        direction = "decreased" if _to_float(change_percent) < 0 else "increased"

        if not drivers:
            return {
                "insufficient_evidence": True,
                "summary": f"{metric} {direction}, but no account-level drivers were supplied.",
            }

        ranked = sorted(drivers, key=lambda d: abs(_to_float(d.get("change", 0))), reverse=True)[:5]
        parts = []
        for driver in ranked:
            change = _to_float(driver.get("change", 0))
            percent = driver.get("change_percent")
            arrow = "up" if change > 0 else "down"
            percent_text = f" {abs(_to_float(percent)):.1f}%" if percent is not None else ""
            parts.append(f"{driver.get('name', 'Unknown')} {arrow}{percent_text}")

        return {
            "summary": (
                f"{metric} {direction}"
                + (f" {abs(_to_float(change_percent)):.1f}%" if change_percent is not None else "")
                + f". Main drivers: {'; '.join(parts)}."
            ),
            "drivers": [
                {
                    "name": driver.get("name"),
                    "account_id": driver.get("account_id"),
                    "change": driver.get("change"),
                    "change_percent": driver.get("change_percent"),
                    "direction": "increase" if _to_float(driver.get("change", 0)) > 0 else "decrease",
                }
                for driver in ranked
            ],
            "confidence": 0.9,
        }

    def _summarise(self, prompt: str, context: dict) -> dict:
        # If the caller already computed a sentence, that is better than
        # anything this provider can assemble — return it unchanged.
        computed = context.get("computed_answer") or context.get("computed_summary")
        if computed:
            return {"summary": str(computed), "confidence": 0.95}

        facts = _scalar_facts(context.get("facts") or context.get("metrics") or {})
        if not facts:
            return {"insufficient_evidence": True, "summary": "No figures were supplied to summarise."}
        parts = [f"{_humanise(key)} is {value}" for key, value in list(facts.items())[:6]]
        return {"summary": ". ".join(parts) + ".", "confidence": 0.95}

    def _reconcile(self, prompt: str, context: dict) -> dict:
        """Only ever selects from candidate ids provided in the context."""
        candidates = context.get("candidates") or []
        if not candidates:
            return {
                "insufficient_evidence": True,
                "reasoning": "No candidate ledger lines were supplied for this bank transaction.",
            }
        best = max(candidates, key=lambda c: _to_float(c.get("score", 0)))
        if _to_float(best.get("score", 0)) < 40:
            return {
                "insufficient_evidence": True,
                "reasoning": (
                    "The strongest candidate scores too low to suggest a match; "
                    "this needs a human."
                ),
            }
        return {
            "journal_line_id": best.get("journal_line_id"),
            "confidence": min(0.9, _to_float(best.get("score", 0)) / 100),
            "reasoning": (
                f"Best available candidate: {best.get('reason', 'amount and date align')}."
            ),
        }

    def _extract_document(self, prompt: str, context: dict) -> dict:
        """Regex extraction over the supplied document text — never invented."""
        text = str(context.get("document_text", ""))
        if not text.strip():
            return {
                "insufficient_evidence": True,
                "reasoning": "No readable text was supplied for this document.",
            }

        fields: dict[str, Any] = {}
        confidence: dict[str, float] = {}

        gstin = re.search(r"\b\d{2}[A-Z]{5}\d{4}[A-Z]\d[Z][A-Z\d]\b", text)
        if gstin:
            fields["gstin"] = gstin.group(0)
            confidence["gstin"] = 0.95

        invoice_number = re.search(
            r"(?:invoice|bill|inv)\s*(?:no\.?|number|#)?\s*[:\-]?\s*([A-Z0-9][A-Z0-9/\-]{2,25})",
            text,
            re.IGNORECASE,
        )
        if invoice_number:
            fields["invoice_number"] = invoice_number.group(1).strip()
            confidence["invoice_number"] = 0.75

        date_match = re.search(r"\b(\d{1,2}[/-]\d{1,2}[/-]\d{2,4}|\d{4}-\d{2}-\d{2})\b", text)
        if date_match:
            fields["invoice_date"] = date_match.group(1)
            confidence["invoice_date"] = 0.7

        total = re.search(
            r"(?:grand\s+total|total\s+amount|net\s+payable|total)\s*[:\-]?\s*(?:INR|Rs\.?|₹)?\s*([\d,]+\.?\d{0,2})",
            text,
            re.IGNORECASE,
        )
        if total:
            fields["total"] = total.group(1).replace(",", "")
            confidence["total"] = 0.7

        return {
            "fields": fields,
            "field_confidence": confidence,
            "needs_review": len(fields) < 3,
            "reasoning": (
                f"Extracted {len(fields)} field(s) by pattern matching. "
                "Fields not present in the document text were left empty rather than guessed."
            ),
        }

    def _tds_section(self, prompt: str, context: dict) -> dict:
        """Suggest a section from the *configured* list only."""
        description = str(context.get("description", "")).lower()
        sections = context.get("available_sections") or []
        if not sections:
            return {"insufficient_evidence": True, "reasoning": "No TDS sections are configured."}

        mapping = [
            (["professional", "consult", "technical", "audit", "legal", "advisory"], "194J"),
            (["contract", "contractor", "labour", "job work", "works"], "194C"),
            (["rent", "lease", "premises"], "194I"),
            (["commission", "brokerage"], "194H"),
            (["interest"], "194A"),
        ]
        configured = {str(s.get("section", s)): s for s in sections}
        for keywords, section in mapping:
            if any(keyword in description for keyword in keywords) and section in configured:
                return {
                    "section": section,
                    "confidence": 0.75,
                    "reasoning": (
                        f"The description mentions "
                        f"'{next(k for k in keywords if k in description)}', which maps to "
                        f"section {section}."
                    ),
                }
        return {
            "insufficient_evidence": True,
            "reasoning": (
                "The description does not clearly indicate a nature of payment; "
                "an accountant should pick the section."
            ),
        }

    def _close_summary(self, prompt: str, context: dict) -> dict:
        # The caller's computed sentence already reads well; prefer it.
        computed = context.get("computed_summary")
        findings = context.get("findings") or []
        blocking = [f for f in findings if f.get("blocking")]
        return {
            "summary": (
                str(computed)
                if computed
                else f"{len(findings)} check(s) reviewed; {len(blocking)} blocking issue(s) remain."
                if findings
                else "No close findings were supplied."
            ),
            "blocking_count": len(blocking),
            "confidence": 0.95,
        }

    def _answer_question(self, prompt: str, context: dict) -> dict:
        """Prefer the caller's computed answer; never restate raw JSON as prose."""
        question = context.get("question", "")
        # Callers name this either way; accept both. Missing it entirely drops
        # to the raw-fact branch below, which reads like a database dump rather
        # than an answer, so this lookup is load-bearing.
        computed = context.get("verified_figures") or context.get("computed_answer")
        if computed:
            return {"answer": str(computed), "confidence": 0.95, "question": question}

        facts = _scalar_facts(context.get("data") or context.get("facts") or {})
        if not facts:
            return {
                "insufficient_evidence": True,
                "answer": (
                    "I don't have enough evidence in the books to answer that. "
                    "Try rephrasing, or check that the relevant records exist."
                ),
            }
        lines = [f"{_humanise(key)} is {value}" for key, value in list(facts.items())[:8]]
        return {
            "answer": "From the ledger: " + "; ".join(lines) + ".",
            "confidence": 0.9,
            "question": question,
        }

    def _unknown(self, prompt: str, context: dict) -> dict:
        return {
            "insufficient_evidence": True,
            "reasoning": (
                "The deterministic provider has no handler for this task. "
                "Configure Gemini, Grok or Ollama for free-form reasoning."
            ),
        }


# ------------------------------------------------------------- helpers -----

def _parse_context(prompt: str) -> dict:
    """Read the ``<context>{json}</context>`` block agents attach."""
    match = re.search(r"<context>\s*(.+?)\s*</context>", prompt, re.DOTALL)
    if not match:
        return {}
    try:
        parsed = json.loads(match.group(1))
        return parsed if isinstance(parsed, dict) else {"data": parsed}
    except json.JSONDecodeError:
        return {}


def _detect_task(prompt: str, context: dict) -> str:
    explicit = re.search(r"<task>\s*([a-z_]+)\s*</task>", prompt)
    if explicit:
        return explicit.group(1)
    lowered = prompt.lower()
    if "categoris" in lowered or "categoriz" in lowered:
        return "categorise"
    if "variance" in lowered or "why did" in lowered:
        return "explain_variance"
    if "reconcil" in lowered or "match" in lowered:
        return "reconcile"
    if "extract" in lowered:
        return "extract_document"
    if "tds" in lowered and "section" in lowered:
        return "tds_section"
    return "answer_question"


def _to_float(value: Any) -> float:
    try:
        return float(str(value).replace(",", ""))
    except (TypeError, ValueError):
        return 0.0


def _humanise(key: str) -> str:
    return str(key).replace("_", " ").strip().capitalize()


def _scalar_facts(payload: Any, *, prefix: str = "", depth: int = 0) -> dict[str, Any]:
    """Flatten a context payload down to plain scalar facts.

    Nested dicts and lists are summarised (or counted) rather than dumped, so
    the deterministic provider never emits raw JSON as if it were prose.
    """
    if depth > 2 or not isinstance(payload, dict):
        return {}
    facts: dict[str, Any] = {}
    for key, value in payload.items():
        label = f"{prefix}{key}"
        if isinstance(value, (str, int, float)) and not isinstance(value, bool):
            facts[label] = value
        elif isinstance(value, bool):
            facts[label] = "yes" if value else "no"
        elif isinstance(value, list):
            if value:
                facts[f"{label} count"] = len(value)
        elif isinstance(value, dict):
            facts.update(_scalar_facts(value, prefix=f"{label} ", depth=depth + 1))
    return facts
