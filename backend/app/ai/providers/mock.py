"""The deterministic Mock provider — always available, never fabricates.

This is what keeps the product fully functional with zero API keys. It is not
a stub that returns lorem ipsum: it reads the structured context the agent
supplies and answers with keyword/heuristic logic over *that data only*.

Two rules it never breaks:

* It only ever names accounts, vendors or ids that were given to it in the
  prompt context. It cannot invent an account code or an invoice number.
* When the context does not support an answer, it says so
  (``insufficient_evidence: true``) instead of guessing.

Because agents do their accounting work deterministically and use the model for
classification and wording, Mock-mode output is genuinely useful — just less
fluent than a real model.
"""
